    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        int row = TblToko.getSelectedRow();
        if (row != -1) {
            try {
                int id = (int) TblToko.getValueAt(row, 0);
                Toko tokoUpdate = new Toko(id, txtNamaToko.getText(), txtAlamatToko.getText(), txtNamaPemilik.getText());
                tokoDao.updateToko(tokoUpdate);
                JOptionPane.showMessageDialog(this, "Data Berhasil Diperbarui!");
                loadData(); // Refresh tabel
                clearFields();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal Update: " + e.getMessage());
            }
        } else {
            JOptionPane.showMessageDialog(this, "Pilih data di tabel terlebih dahulu!");
        }    
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        int row = TblToko.getSelectedRow();
        if (row != -1) {
            int confirm = JOptionPane.showConfirmDialog(this, "Yakin hapus toko ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                try {
                    int id = (int) TblToko.getValueAt(row, 0);
                    tokoDao.deleteToko(id);
                    loadData(); // Refresh tabel
                    clearFields();
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Gagal Hapus: " + e.getMessage());
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Pilih data di tabel yang ingin dihapus!");
        }
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnKelolaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnKelolaActionPerformed
        int row = TblToko.getSelectedRow();

        if (row != -1) {
            try {
                // PERBAIKAN: Ambil dari index 1 (Kolom ID), bukan index 0 (Kolom No)
                int idToko = (int) TblToko.getValueAt(row, 1);

                FrameOperasional operasional = new FrameOperasional(idToko);
                operasional.setVisible(true);
                this.dispose();

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal membuka menu operasional: " + e.getMessage());
            }
        } else {
            JOptionPane.showMessageDialog(this, "Silahkan pilih toko dari tabel terlebih dahulu untuk dikelola!");
        }
    }//GEN-LAST:event_btnKelolaActionPerformed

    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        try {
            String nama = txtNamaToko.getText();
            String alamat = txtAlamatToko.getText();
            String pemilik = txtNamaPemilik.getText();

            if (nama.isEmpty() || alamat.isEmpty() || pemilik.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Semua input harus diisi!");
                return;
            }

            // PERBAIKAN: Tangkap ID yang dikembalikan (int)
            int idTokoBaru = tokoDao.tambahToko(nama, alamat, pemilik);

            JOptionPane.showMessageDialog(this, "Toko Berhasil Ditambahkan dengan ID: " + idTokoBaru);
            loadData(); // Refresh tabel agar ID muncul di tabel
            clearFields();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal Tambah: " + e.getMessage());
        }
    }//GEN-LAST:event_btnTambahActionPerformed

    private void TblTokoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TblTokoMouseClicked
        int row = TblToko.getSelectedRow();
        if (row != -1) {
            // PERBAIKAN: Index disesuaikan dengan kolom di loadData()
            // Index 1 = Nama, Index 2 = Alamat, Index 3 = Pemilik
            txtNamaToko.setText(TblToko.getValueAt(row, 2).toString());
            txtAlamatToko.setText(TblToko.getValueAt(row, 3).toString());
            txtNamaPemilik.setText(TblToko.getValueAt(row, 4).toString());
        }
    }//GEN-LAST:event_TblTokoMouseClicked

