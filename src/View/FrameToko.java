    private void loadData() {
        // 1. Tambahkan "No" ke dalam header
        String[] header = {"No", "ID", "Nama Toko", "Alamat", "Pemilik"};

        model = new DefaultTableModel(header, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Menonaktifkan edit langsung
            }
        };

        try {
            List<Toko> daftar = tokoDao.getAllToko();
            int noUrut = 1; // Inisialisasi penghitung nomor

            for (Toko t : daftar) {
                // 2. Masukkan noUrut ke index 0, dan geser data lainnya
                Object[] row = {
                    noUrut++, 
                    t.getIdToko(), 
                    t.getNamaToko(), 
                    t.getAlamatToko(), 
                    t.getPemilikToko()
                };
                model.addRow(row);
            }
            TblToko.setModel(model);
            
            aturLebarKolom();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
        }
    }
    
