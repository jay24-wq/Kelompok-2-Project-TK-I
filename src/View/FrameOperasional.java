    private void btnEditProdukActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditProdukActionPerformed
       int row = tblProduk.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Silakan pilih produk pada tabel yang ingin diedit!");
            return;
        }

        try {
            int id = Integer.parseInt(tblProduk.getValueAt(row, 1).toString());
            String nama = tblProduk.getValueAt(row, 2).toString();
            double harga = Double.parseDouble(tblProduk.getValueAt(row, 4).toString());

            Produk p = new Produk();
            p.setIdProduk(id);
            p.setNamaProduk(nama);
            p.setHarga(harga);

            // --- TAMBAHKAN BAGIAN INI ---
            // Kita ambil daftar kategori asli dari database berdasarkan ID Produk
            // Pastikan pDao memiliki method getKategoriByProdukId
            List<Kategori> daftarKategori = pDao.getKategoriByProdukId(id);
            p.setDaftarKategori(daftarKategori); 
            // ----------------------------

            DialogEditProduk dialog = new DialogEditProduk(this, true, this.idToko, p);
            dialog.setLocationRelativeTo(this);
            dialog.setVisible(true);

            loadTabelProduk();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal memproses data edit: " + e.getMessage());
            e.printStackTrace(); // Agar kamu bisa lihat error detail di console
        }

    }//GEN-LAST:event_btnEditProdukActionPerformed

    private void btnHapusProdukActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusProdukActionPerformed
        int row = tblProduk.getSelectedRow();
    
        if (row != -1) {
            // Ambil ID dari index 1, Nama dari index 2
            int id = Integer.parseInt(tblProduk.getValueAt(row, 1).toString());
            String nama = tblProduk.getValueAt(row, 2).toString();

            int konfirmasi = JOptionPane.showConfirmDialog(this, 
                    "Apakah Anda yakin ingin menghapus produk '" + nama + "'?", 
                    "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);

            if (konfirmasi == JOptionPane.YES_OPTION) {
                try {
                    pDao.deleteProduk(id);
                    JOptionPane.showMessageDialog(this, "Produk berhasil dihapus!");
                    loadTabelProduk();
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Gagal hapus produk: " + e.getMessage());
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Pilih produk yang ingin dihapus terlebih dahulu!");
        }
    }//GEN-LAST:event_btnHapusProdukActionPerformed

