    private void loadDetailToko() {
        try {
            Toko t = tDao.getTokoById(this.idToko);
            if (t != null) {
                lblNamaToko.setText(t.getNamaToko());
                lblIdToko.setText("ID : " + t.getIdToko());
                lblAlamatToko.setText("Alamat : " + t.getAlamatToko());
                lblPemilikToko.setText("Pemilik : " + t.getPemilikToko());
            }
        } catch (Exception e) {
            System.err.println("Gagal load detail toko: " + e.getMessage());
        }
    }
    
    public void loadTabelProduk() {
        // 1. Definisikan header dengan 5 kolom (No, ID, Nama, Kategori, Harga)
    String[] header = {"No", "ID Produk", "Nama Produk", "Kategori", "Harga"};
    DefaultTableModel model = new DefaultTableModel(header, 0) {
        @Override
        public boolean isCellEditable(int row, int column) { return false; }
    };

    try {
        List<Produk> list = pDao.getAllProduk(this.idToko);
        int no = 1;
        for (Produk p : list) {
            // 2. Masukkan data sesuai urutan header (Kategori di index 3)
            Object[] row = {
                no++, 
                p.getIdProduk(), 
                p.getNamaProduk(), 
                p.getKategoriTampilan(), // Data dari GROUP_CONCAT di DAO
                p.getHarga()
            };
            model.addRow(row);
        }
        tblProduk.setModel(model);

        // 3. Atur Lebar Kolom agar rapi
        tblProduk.getColumnModel().getColumn(0).setPreferredWidth(40); // No
        tblProduk.getColumnModel().getColumn(1).setPreferredWidth(70); // ID
        tblProduk.getColumnModel().getColumn(2).setPreferredWidth(150); // Nama
        tblProduk.getColumnModel().getColumn(3).setPreferredWidth(150); // Kategori
        tblProduk.getColumnModel().getColumn(4).setPreferredWidth(100); // Harga
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal load produk: " + e.getMessage());
    }
    }
    
    public void loadTabelKategori() {
        // Menambahkan kolom "No" di index 0
        String[] header = {"No", "ID Kategori", "Nama Kategori"};
        DefaultTableModel model = new DefaultTableModel(header, 0) {
            @Override
            public boolean isCellEditable(int row, int column) { return false; }
        };

        try {
            List<Kategori> list = kDao.getAllKategori(this.idToko);
            int no = 1;
            for (Kategori k : list) {
                Object[] row = {no++, k.getIdKategori(), k.getNamaKategori()};
                model.addRow(row);
            }
            tblKategori.setModel(model);

            // Atur Lebar Kolom
            tblKategori.getColumnModel().getColumn(0).setPreferredWidth(35);
            tblKategori.getColumnModel().getColumn(0).setMaxWidth(50);
            tblKategori.getColumnModel().getColumn(1).setPreferredWidth(70); // ID Kategori
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal load kategori: " + e.getMessage());
        }
    }
    
