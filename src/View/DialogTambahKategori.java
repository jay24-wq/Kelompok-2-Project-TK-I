    private void setupPlaceholder() {
        // Set teks awal ke placeholder dan warna abu-abu
        txtNamaKategori.setText(PLACEHOLDER_TEXT);
        txtNamaKategori.setForeground(Color.GRAY);

        // Tambahkan Listener untuk menangani klik (Focus)
        txtNamaKategori.addFocusListener(new FocusAdapter() {
            @Override
            public void focusGained(FocusEvent e) {
                // Jika teks masih placeholder, hapus saat diklik
                if (txtNamaKategori.getText().equals(PLACEHOLDER_TEXT)) {
                    txtNamaKategori.setText("");
                    txtNamaKategori.setForeground(Color.BLACK);
                }
            }

            @Override
            public void focusLost(FocusEvent e) {
                // Jika ditinggalkan dalam keadaan kosong, munculkan lagi placeholder
                if (txtNamaKategori.getText().trim().isEmpty()) {
                    txtNamaKategori.setText(PLACEHOLDER_TEXT);
                    txtNamaKategori.setForeground(Color.GRAY);
                }
            }
        });
    }

