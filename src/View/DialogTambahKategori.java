    private void btnTambahKategoriActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahKategoriActionPerformed
        String nama = txtNamaKategori.getText().trim();

        // 3. Validasi: Jangan izinkan kosong ATAU isi placeholder tersimpan
        if (nama.isEmpty() || nama.equals(PLACEHOLDER_TEXT)) {
            JOptionPane.showMessageDialog(this, "Nama kategori tidak boleh kosong!");
            return;
        }

        try {
            kDao.tambahKategori(this.idToko, nama); 
            JOptionPane.showMessageDialog(this, "Kategori '" + nama + "' berhasil ditambahkan!");
            this.dispose(); 
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menambahkan kategori: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnTambahKategoriActionPerformed

